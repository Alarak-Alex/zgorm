//! SQL syntax and capability differences kept out of ORM behavior.

pub const Dialect = enum {
    postgresql,
    mysql,
    sqlite,

    pub fn identifierQuote(comptime self: Dialect) u8 {
        return switch (self) {
            .postgresql, .sqlite => '"',
            .mysql => '`',
        };
    }

    pub fn maxParameters(comptime self: Dialect) usize {
        return switch (self) {
            .postgresql => 65_535,
            .mysql => 65_535,
            .sqlite => 32_766,
        };
    }

    pub fn supportsReturning(comptime self: Dialect) bool {
        return self != .mysql;
    }

    pub fn supportsDistinctOn(comptime self: Dialect) bool {
        return self == .postgresql;
    }

    pub fn supportsForUpdate(comptime self: Dialect) bool {
        return self != .sqlite;
    }

    pub fn supportsTransactionalDdl(comptime self: Dialect) bool {
        return self != .mysql;
    }

    pub fn supportsAdvisoryLocks(comptime self: Dialect) bool {
        return self == .postgresql;
    }

    pub fn autoIncrementClause(comptime self: Dialect) []const u8 {
        return switch (self) {
            .postgresql => "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            .mysql => "AUTO_INCREMENT PRIMARY KEY",
            .sqlite => "PRIMARY KEY AUTOINCREMENT",
        };
    }
};
